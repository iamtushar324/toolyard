-- Postgres baseline: the whole toolyard schema as it stands after the SQLite
-- migrations up to and including 0039_key_canaries.sql, applied in one
-- transaction to an empty database. The runner then records every SQLite
-- migration name up to 0039_key_canaries.sql in schema_migrations, so both
-- engines hold the same names. From 0040 on, each migration is a pair of files
-- with the same name in migrations/sqlite and migrations/postgres.
--
-- Type rules (keep them for every later Postgres migration):
--   INTEGER                            -> BIGINT (millisecond timestamps overflow INTEGER)
--   INTEGER PRIMARY KEY AUTOINCREMENT  -> BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
--   BLOB                               -> BYTEA
--   REAL                               -> DOUBLE PRECISION
--   JSON kept in TEXT                  -> TEXT (cast to jsonb only in the queries that look inside)
--   0/1 flags                          -> BIGINT, never BOOLEAN (the SQL compares them to 0 and 1)
-- The database must use C collation so text ordering matches SQLite.
--
-- Left out on purpose: the dropped policies table (0013), and the unused lake
-- items (lake_ingest_runs and lake_saved_queries from 0009, events.lake_synced
-- and idx_events_unsynced from 0018).

